  try { language = localStorage.getItem('recylight-language') || 'en'; } catch {}
  const originals = new Map();
  const originalAttributes = new Map();
  const languageToggle = document.querySelector('#language-toggle');
  const menu = document.querySelector('#language-menu');
  const languageCode = document.querySelector('#language-code');
  const codes = { en: 'EN', rw: 'RW', sw: 'SW' };
  function translateString(text) {
    return copy[language]?.[text] || text;
  }
  function translatePage(root = document.body) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      if (!originals.has(node)) originals.set(node, node.nodeValue);
      const source = originals.get(node);
      const trimmed = source.trim();
      if (!trimmed) continue;
      const translated = translateString(trimmed);
      if (translated !== trimmed) node.nodeValue = source.replace(trimmed, translated);
      else if (language === 'en') node.nodeValue = source;
    }
    const attrs = ['placeholder','aria-label','title','alt','data-notice'];
    root.querySelectorAll('*').forEach(element => {
      if (!originalAttributes.has(element)) originalAttributes.set(element, {});
      const sourceAttrs = originalAttributes.get(element);
      for (const attr of attrs) {
        if (!element.hasAttribute(attr)) continue;
        if (sourceAttrs[attr] === undefined) sourceAttrs[attr] = element.getAttribute(attr);
        const source = sourceAttrs[attr];
        const translated = translateString(source);
        if (element.getAttribute(attr) !== translated) element.setAttribute(attr, translated);
      }
    });
  }
  function applyLanguage() {
    languageCode.textContent = codes[language];
    languageToggle.setAttribute('aria-label', `${translateString('Choose language')} (${language.toUpperCase()})`);
    menu.querySelectorAll('[data-language]').forEach(option => option.setAttribute('aria-checked', String(option.dataset.language === language)));
    document.documentElement.lang = language;
    translatePage();
  }
